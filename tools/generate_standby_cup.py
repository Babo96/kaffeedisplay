#!/usr/bin/env python3
"""Build one lightweight native LVGL I8 image from the editable espresso SVG.

Generation-time requirements only: cairosvg, Pillow.
The ESP32 renders a static 8-bit palette image directly from firmware flash.
No SVG parser, filesystem, PNG decoder or allocation is required at runtime.
"""

from pathlib import Path
import argparse
import io

ROOT = Path(__file__).resolve().parents[1]
SVG = ROOT / "assets/standby/espresso.svg"
HEADER = ROOT / "build/standby/standby_cup_generated.hpp"
WIDTH = 242
HEIGHT = 175
PALETTE_ENTRIES = 256


def generate() -> str:
    import cairosvg
    from PIL import Image

    png = cairosvg.svg2png(url=str(SVG), output_width=WIDTH, output_height=HEIGHT)
    rgb = Image.open(io.BytesIO(png)).convert("RGB")
    indexed = rgb.quantize(
        colors=240, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.FLOYDSTEINBERG
    )
    colors = indexed.getpalette()
    assert colors is not None and len(colors) % 3 == 0
    # Pillow emits exactly 240 entries when asked for 240 colours, while
    # LVGL I8 requires a full 256-entry palette before its pixel data.
    colors.extend([16, 13, 12] * (PALETTE_ENTRIES - len(colors) // 3))
    assert len(colors) == PALETTE_ENTRIES * 3
    payload = bytearray()
    # LVGL stores its full 256-entry ARGB8888 lookup table BEFORE the I8 pixels.
    # On the ESP32 (little endian) each palette color is stored as B, G, R, A.
    for index in range(PALETTE_ENTRIES):
        r, g, b = colors[3 * index:3 * index + 3]
        payload.extend((b, g, r, 255))
    payload.extend(indexed.tobytes())

    expected = PALETTE_ENTRIES * 4 + WIDTH * HEIGHT
    assert len(payload) == expected, (len(payload), expected)

    byte_lines = [
        "    " + ", ".join(f"0x{byte:02x}" for byte in payload[start:start + 20]) + ","
        for start in range(0, len(payload), 20)
    ]
    return (
        "// Generated by tools/generate_standby_cup.py from assets/standby/espresso.svg\n"
        "// Do not hand-edit.\n"
        "// clang-format off\n"
        "#pragma once\n"
        '#include "lvgl.h"\n'
        "namespace kaffee::ui {\n"
        "LV_ATTRIBUTE_MEM_ALIGN static const uint8_t standby_cup_data[] = {\n"
        + "\n".join(byte_lines)
        + "\n};\n"
        "static const lv_image_dsc_t standby_cup_image = {\n"
        "    { LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_I8, 0, 242, 175, 242, 0 },\n"
        "    sizeof(standby_cup_data), standby_cup_data\n"
        "};\n"
        "}  // namespace kaffee::ui\n"
        "// clang-format on\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Verify generated data is in sync")
    parser.add_argument(
        "--output", type=Path, default=HEADER, help="Generated header path"
    )
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not args.output.exists() or args.output.read_text() != output:
            parser.error(f"Standby image is outdated: regenerate {args.output}")
        print("PASS: LVGL I8 palette image matches editable SVG")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(output)
        print(f"Generated {args.output} ({PALETTE_ENTRIES * 4 + WIDTH * HEIGHT} image bytes)")


if __name__ == "__main__":
    main()
